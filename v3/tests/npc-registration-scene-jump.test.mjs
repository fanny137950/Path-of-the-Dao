import test from 'node:test';
import assert from 'node:assert/strict';
import {initialV3World,commitV3Turn,validatedWorld,playerWorld,developerWorld} from '../server/world.mjs';
import {registerNamedNPCs} from '../server/npc-registration.mjs';
import {sceneJumpPlan,prepareSceneJump} from '../server/scene-jump.mjs';
import {elapsedMinutes} from '../server/living-world.mjs';
test('new named rival is persisted under one canonical ID and visible to developer',()=>{
 const w=initialV3World('ye-chong');
 const initial=Object.keys(w.npcs).length;
 const reply='少年揚起卷冊：「我叫葉沖，跟你一樣來報名收徒。」他得意地笑了。';
 const next=commitV3Turn(w,'你是誰',reply,'new-npc-1');
 const created=Object.values(next.npcs).filter(n=>n.name==='葉沖');
 assert.equal(created.length,1);
 assert.equal(created[0].source,'ai-generated');
 assert.equal(created[0].where,'太虛宗山門');
 assert.equal(created[0].realm,'未公開');
 assert.equal(Object.keys(next.npcs).length,initial+1);
 assert.ok(developerWorld(next).characters[created[0].id]);
 assert.equal(playerWorld(next).characters,undefined);
 assert.ok(created[0].memories.some(m=>m.text.includes('葉沖')));
 const saved=validatedWorld(JSON.parse(JSON.stringify(next)));
 assert.equal(Object.values(saved.npcs).filter(n=>n.name==='葉沖').length,1);
 const again=commitV3Turn(saved,'你的靈根呢','葉沖說：「火靈根。」','new-npc-2');
 assert.equal(Object.values(again.npcs).filter(n=>n.name==='葉沖').length,1);
});
test('GM_STATE NPC proposal is accepted only if narrated and does not override existing identities',()=>{
 const w=initialV3World('npc-proposal');
 const proposal={name:'白敬蘭',role:'宗門接引弟子',peak:'青雲峰',traits:['認真'],goal:'完成考核接引'};
 const raw='白敬蘭是一名宗門接引弟子，走到洛河身旁。\n<!--GM_STATE:'+JSON.stringify({newNPCs:[proposal]})+'-->';
 const first=commitV3Turn(w,'觀察周圍',raw,'named-1');
 const found=Object.values(first.npcs).filter(n=>n.name==='白敬蘭');
 assert.equal(found.length,1);
 assert.equal(found[0].role,'宗門接引弟子');
 const duplicate=registerNamedNPCs(first,'韓守一叫了一聲，白敬蘭應了一聲。',[proposal]);
 assert.deepEqual(duplicate.created,[]);
 assert.equal(Object.values(first.npcs).filter(n=>n.name==='白敬蘭').length,1);
});
test('scene jumping to recruitment changes game clock and scheduled milestones without player consent',()=>{
 const w=initialV3World('scene-skip');
 const plan=sceneJumpPlan(w,'直接進到收徒');
 assert.equal(plan.minutes,300);
 assert.equal(plan.target,780);
 const prepared=prepareSceneJump(w,plan);
 assert.equal(elapsedMinutes(prepared),780);
 assert.equal(elapsedMinutes(w),480);
 assert.ok(prepared.eventCalendar.events.find(e=>e.id==='twelve-peaks-selection').completed.includes('open'));
 assert.ok(prepared.events.some(e=>e.source==='event-calendar'));
 assert.ok(prepared.events.some(e=>e.source==='npc-agency'));
 const finished=commitV3Turn(prepared,'直接進到收徒','十二峰接引代表開始核對初選名冊。','skip-1',{advanceMinutes:0,sceneJump:{minutes:plan.minutes,eventId:plan.eventId}});
 assert.equal(elapsedMinutes(finished),780);
 assert.equal(finished.events.find(e=>e.requestId==='skip-1').sceneJump.minutes,300);
 assert.equal(finished.protagonist.spiritualRoot,'未測定');
 assert.equal(finished.location,'太虛宗山門');
 assert.deepEqual(finished.messages.at(-2),{role:'user',content:'直接進到收徒'});
});
test('non pacing dialogue is not treated as a request to fast forward',()=>{
 const w=initialV3World('normal-talk');
 assert.equal(sceneJumpPlan(w,'你也知道初評重要吧'),null);
 assert.equal(sceneJumpPlan(w,'我直接衝向對手'),null);
 assert.equal(sceneJumpPlan(w,'繼續'),null);
 assert.equal(sceneJumpPlan(w,'跳到宗門論道').label,'年度論道');
});
